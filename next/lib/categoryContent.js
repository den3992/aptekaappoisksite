const GEN = { msk: 'Москвы', spb: 'Санкт-Петербурга' };
const LOC = { msk: 'Москве', spb: 'Санкт-Петербурге' };

function fill(str, city) {
  const g = GEN[city] || GEN.msk;
  const l = LOC[city] || LOC.msk;
  return String(str).replace(/\{gen\}/g, g).replace(/\{loc\}/g, l);
}

// Возвращает контент категории с подставленным городом, либо null.
export function categoryContent(slug, city) {
  const c = CATEGORY_CONTENT[slug];
  if (!c) return null;
  return {
    body: (c.body || []).map((p) => fill(p, city)),
    faq: (c.faq || []).map((qa) => ({ q: fill(qa.q, city), a: fill(qa.a, city) })),
    related: (c.related || []).filter((s) => CAT_TITLES[s]),
  };
}
