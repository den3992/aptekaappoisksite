// Select up to 100 medications to enrich.
// Priority: is_canonical, no enrichment yet, MNN in popular list,
// then ordered by number of variants (= more packaging = more searches), then name.

const POPULAR_MNN = [
  "ПАРАЦЕТАМОЛ","ИБУПРОФЕН","АЦЕТИЛСАЛИЦИЛОВАЯ КИСЛОТА","ОМЕПРАЗОЛ",
  "ЛОРАТАДИН","ЦЕТИРИЗИН","ХЛОРОПИРАМИН","ДРОТАВЕРИН",
  "МЕТАМИЗОЛ НАТРИЯ","КЕТОПРОФЕН","ЛОПЕРАМИД","СМЕКТИТ ДИОКТАЭДРИЧЕСКИЙ",
  "АМБРОКСОЛ","БРОМГЕКСИН","АЦЕТИЛЦИСТЕИН",
  "АМОКСИЦИЛЛИН","АЗИТРОМИЦИН","ЦИПРОФЛОКСАЦИН","МЕТРОНИДАЗОЛ","ФЛУКОНАЗОЛ",
  "КОЛЕКАЛЬЦИФЕРОЛ","АСКОРБИНОВАЯ КИСЛОТА",
  "МАГНИЯ ЛАКТАТ","МАГНИЯ ЦИТРАТ","МЕЛЬДОНИЙ",
  "ФУРОСЕМИД","ЭНАЛАПРИЛ","ЛОЗАРТАН","АМЛОДИПИН","БИСОПРОЛОЛ","МЕТОПРОЛОЛ",
  "ГЛИЦИН","МЕЛАТОНИН","НИМЕСУЛИД","ДИКЛОФЕНАК",
  "АНАСТРОЗОЛ","ТАМОКСИФЕН","ИНСУЛИН ГЛАРГИН","МЕТФОРМИН",
  "АМИОДАРОН","ВАРФАРИН","ГЕПАРИН НАТРИЯ",
  "СУМАТРИПТАН","БЕТАГИСТИН",
  "АТОРВАСТАТИН","РОЗУВАСТАТИН","СИМВАСТАТИН",
  "КЕТОТИФЕН","ДЕЗЛОРАТАДИН","ИВЕРМЕКТИН","ОСЕЛЬТАМИВИР","АЦИКЛОВИР",
  "УМИФЕНОВИР","РИБАВИРИН",
  "ЭСОМЕПРАЗОЛ","ПАНТОПРАЗОЛ","ФАМОТИДИН","ДОМПЕРИДОН","МЕТОКЛОПРАМИД",
  "АТРОПИН","ПЛАТИФИЛЛИН","СПИРОНОЛАКТОН","ИНДАПАМИД",
];

const docs = db.medications.aggregate([
  { $match: {
      enrichment: { $exists: false },
      $or: [{ is_canonical: true }, { is_canonical: { $exists: false } }],
      mnn: { $in: POPULAR_MNN },
  }},
  { $addFields: {
      _vc: { $size: { $ifNull: ["$variants", []] } },
  }},
  { $sort: { _vc: -1, name: 1 } },
  { $limit: 100 },
  { $project: {
      _id: 0,
      slug: 1, name: 1, label_name: 1, mnn: 1, form: 1,
      dosage: 1, manufacturer: 1,
  }},
]).toArray();

print(JSON.stringify(docs));
